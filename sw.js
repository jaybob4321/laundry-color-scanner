/* Laundry Color Scanner service worker (blueprint §15).
 *
 * - One cache per build version; install fails (and the old worker stays)
 *   unless every precached file is fetched and verified.
 * - Cache-first for precached same-origin GETs; navigations inside the scope
 *   get the cached app shell, so HTML, JS, palette, config and worker always
 *   come from the same atomic version.
 * - Never intercepts cross-origin or non-GET requests; never caches images,
 *   uploads or AI responses.
 * - Activation of an update waits for the user ("Reload to update" on Home).
 */

