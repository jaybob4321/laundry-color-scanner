const CACHE_PREFIX = 'laundry-color-scanner-';
const CACHE_NAME = `${CACHE_PREFIX}${PRECACHE.version}`;
const scopeUrl = new URL(self.registration.scope);
const PRECACHE_PATHS = new Set(PRECACHE.files.map((f) => new URL(f, scopeUrl).pathname));

async function verifyCache() {
  const cache = await caches.open(CACHE_NAME);
  const missing = [];
  for (const file of PRECACHE.files) {
    const response = await cache.match(new URL(file, scopeUrl));
    if (!response || !response.ok) missing.push(file);
  }
  return { ok: missing.length === 0, version: PRECACHE.version, missing };
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE_NAME);
      // addAll is atomic: any failed file rejects install and keeps the old worker.
      await cache.addAll(PRECACHE.files.map((f) => new Request(new URL(f, scopeUrl), { cache: 'reload' })));
      const check = await verifyCache();
      if (!check.ok) throw new Error(`Precache incomplete: ${check.missing.join(', ')}`);
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k.startsWith(CACHE_PREFIX) && k !== CACHE_NAME).map((k) => caches.delete(k)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', (event) => {
  const type = event.data?.type;
  if (type === 'SKIP_WAITING') self.skipWaiting();
  else if (type === 'VERIFY_CACHE') {
    event.waitUntil(
      verifyCache()
        .catch(() => ({ ok: false, version: PRECACHE.version, missing: ['*'] }))
        .then((result) => event.ports[0]?.postMessage(result)),
    );
  }
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== scopeUrl.origin || !url.pathname.startsWith(scopeUrl.pathname)) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      (async () => {
        const cache = await caches.open(CACHE_NAME);
        return (await cache.match(new URL('./', scopeUrl))) ?? (await cache.match(new URL('index.html', scopeUrl))) ?? fetch(request);
      })(),
    );
    return;
  }

  if (!PRECACHE_PATHS.has(url.pathname)) return;
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE_NAME);
      // Match on origin + path so cache-busting query strings can't bypass the atomic version.
      return (await cache.match(url.origin + url.pathname)) ?? fetch(request);
    })(),
  );
});
